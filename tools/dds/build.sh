#!/bin/bash
# Builds DDS (the double-dummy solver: github.com/dds-bridge/dds, Apache-2.0) to WebAssembly for
# the Hard bridge bots: src/engine/bots/dds/ddsWasm.js (the wasm inside, so it loads anywhere a
# script does: the bots' worker, the page, and the tests). Single-threaded: no cross-origin
# isolation needed. Pinned versions, so a rebuild gives the same solver:
#
#   tools/dds/build.sh [work-dir]      (needs git, python3 and a few hundred MB; about five minutes)
set -euo pipefail
DDS_VERSION=v2.9.0
EMSDK_VERSION=3.1.61
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
WORK="${1:-${TMPDIR:-/tmp}/dds-build}"
mkdir -p "$WORK"
cd "$WORK"
[ -d dds ] || git clone -q --depth 1 --branch "$DDS_VERSION" https://github.com/dds-bridge/dds.git dds
[ -d emsdk ] || git clone -q --depth 1 https://github.com/emscripten-core/emsdk.git emsdk
(cd emsdk && ./emsdk install "$EMSDK_VERSION" >/dev/null && ./emsdk activate "$EMSDK_VERSION" >/dev/null)
# shellcheck disable=SC1091
source emsdk/emsdk_env.sh >/dev/null 2>&1
# In a browser there's no /proc/meminfo: DDS would find no free memory, so no threads, and stop.
# Say so plainly: one core, a gigabyte (SetResources then caps it at what dds_init asks for).
if ! grep -q __EMSCRIPTEN__ dds/src/System.cpp; then
  python3 - <<'PY'
import re
p = 'dds/src/System.cpp'
s = open(p).read()
anchor = '  (void) System::GetCores(ncores);\n'
assert anchor in s
s = s.replace(anchor, anchor + '\n#ifdef __EMSCRIPTEN__\n  ncores = 1;\n  kilobytesFree = 1024 * 1024;\n  return;\n#endif\n', 1)
open(p, 'w').write(s)
PY
fi
SRC=(dds dump ABsearch ABstats CalcTables DealerPar File Init LaterTricks Memory Moves Par PlayAnalyser
  PBN QuickTricks Scheduler SolveBoard SolverIF System ThreadMgr Timer TimerGroup TimerList TimeStat
  TimeStatList TransTableS TransTableL)
FILES=()
for f in "${SRC[@]}"; do FILES+=("dds/src/$f.cpp"); done
OUT="$ROOT/src/engine/bots/dds/ddsWasm.js"
# (DDS 2.9 leans on headers that older compilers pulled in by themselves)
em++ -O3 -std=c++11 -DNDEBUG -include cstdio -include cstdlib -include cstring -Idds/include -Idds/src "${FILES[@]}" "$HERE/wrapper.cpp" \
  -o "$OUT.tmp.js" \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createDds -sSINGLE_FILE=1 \
  -sENVIRONMENT=web,worker,node -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=33554432 \
  -sEXPORTED_FUNCTIONS=_dds_init,_dds_solve,_dds_table,_malloc,_free \
  -sEXPORTED_RUNTIME_METHODS=HEAP32,HEAPU32 -sFILESYSTEM=0 -sASSERTIONS=0
{
  echo "// Generated by tools/dds/build.sh from DDS $DDS_VERSION (github.com/dds-bridge/dds, Apache License 2.0;"
  echo "// see tools/dds/LICENSE). Don't edit: rebuild."
  echo "/* eslint-disable */"
  echo "// @ts-nocheck"
  cat "$OUT.tmp.js"
} >"$OUT"
rm "$OUT.tmp.js"
cp dds/LICENSE "$HERE/LICENSE"
echo "built $OUT ($(wc -c <"$OUT") bytes)"
